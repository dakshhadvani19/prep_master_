/**
 * process-syllabuses.cjs
 *
 * Reads all PDF files from the `syllabus-pdfs/` folder,
 * extracts their text, and writes src/data/pdfSyllabus.js.
 *
 * Usage:
 *   1. Put PDFs in syllabus-pdfs/ named as the subject ID, e.g. 01ma0106.pdf
 *   2. Run: node process-syllabuses.cjs
 *   3. Commit src/data/pdfSyllabus.js — ExamPortal will use it automatically.
 */

const fs = require('fs');
const path = require('path');
const pdfParse = require('pdf-parse');

const PDF_DIR = path.join(__dirname, 'syllabus-pdfs');
const OUTPUT_FILE = path.join(__dirname, 'src', 'data', 'pdfSyllabus.js');

async function main() {
    if (!fs.existsSync(PDF_DIR)) {
        fs.mkdirSync(PDF_DIR);
        console.log('Created syllabus-pdfs/ folder. Put your PDFs in there and run again.');
        return;
    }

    const files = fs.readdirSync(PDF_DIR).filter(f => f.toLowerCase().endsWith('.pdf'));

    if (files.length === 0) {
        console.log('No PDF files found in syllabus-pdfs/. Add PDFs named as subject IDs (e.g. 01ma0106.pdf).');
        return;
    }

    console.log(`Found ${files.length} PDF(s). Processing...\n`);

    const result = {};
    const errors = [];

    for (const file of files) {
        const subjectId = path.basename(file, '.pdf').split('-')[0].trim();
        const filePath = path.join(PDF_DIR, file);

        try {
            const buffer = fs.readFileSync(filePath);
            const data = await pdfParse(buffer);
            const text = data.text.trim();

            if (text.length < 50) {
                errors.push(`  ⚠  ${file} — extracted text too short (${text.length} chars), skipped. Is it a scanned/image PDF?`);
                continue;
            }

            // Cap at 50,000 chars to keep the JS file reasonable
            result[subjectId] = text.slice(0, 50000);
            console.log(`  ✓  ${file} → subjectId: "${subjectId}" (${text.length} chars)`);
        } catch (e) {
            errors.push(`  ✗  ${file} — failed: ${e.message}`);
        }
    }

    if (errors.length > 0) {
        console.log('\nWarnings/Errors:');
        errors.forEach(e => console.log(e));
    }

    const count = Object.keys(result).length;
    if (count === 0) {
        console.log('\nNo valid PDFs processed. Nothing written.');
        return;
    }

    // Write the output JS file
    const lines = [
        '// AUTO-GENERATED by process-syllabuses.cjs — do not edit manually.',
        `// Generated: ${new Date().toISOString()}`,
        `// Subjects: ${Object.keys(result).join(', ')}`,
        '',
        'export const pdfSyllabus = {',
    ];

    for (const [subjectId, text] of Object.entries(result)) {
        // Escape backticks and backslashes in the text
        const safe = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\${/g, '\\${');
        lines.push(`  ${JSON.stringify(subjectId)}: \`${safe}\`,`);
    }

    lines.push('};');
    lines.push('');

    fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8');
    console.log(`\nDone! Wrote ${count} subject(s) to src/data/pdfSyllabus.js`);
}

main().catch(e => { console.error('Fatal error:', e); process.exit(1); });
